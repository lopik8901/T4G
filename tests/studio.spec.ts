import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('dashboard fits mobile and desktop and offers functional templates', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Good things start with play.' })).toBeVisible()
  await page.screenshot({ path: 'artifacts/careplay-dashboard.png', fullPage: true })
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()
  expect(result.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) }))).toEqual([])
  for (const width of [375, 768, 1440]) { await page.setViewportSize({ width, height: 1000 }); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true) }
  await page.setViewportSize({ width: 375, height: 900 }); await page.screenshot({ path: 'artifacts/careplay-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})

test('create, play, edit, undo, save, reload and launch a garden', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create new game', exact: true }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByLabel('Your activity idea').fill('Create a relaxing garden where two residents grow flowers using their hands.')
  await page.getByRole('button', { name: 'Create my activity' }).click()
  await expect(page.getByRole('heading', { name: 'Collaborative Garden', exact: true })).toBeVisible()
  await expect(page.getByLabel('Participants')).toHaveValue('2')
  await page.getByRole('button', { name: 'Start preview', exact: true }).click()
  await page.locator('.cp-game-object').first().click()
  await expect(page.locator('.cp-stage-instruction')).toHaveText('1 flowers grown together')
  await page.getByLabel('Ask for a change').fill('Make the flowers twice as big and slow down the game')
  await page.getByRole('button', { name: 'Send request' }).click()
  await expect(page.getByLabel('Object size', { exact: true })).toHaveValue('2')
  expect(Number(await page.getByLabel('Movement speed', { exact: true }).inputValue())).toBeLessThan(0.65)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByLabel('Object size', { exact: true })).toHaveValue('1.2')
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(page.getByLabel('Object size', { exact: true })).toHaveValue('2')
  await page.getByLabel('Activity title').fill('Our little garden')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Saved on this device', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'artifacts/careplay-editor.png', fullPage: true })
  await page.reload()
  await page.getByRole('button', { name: 'Edit Our little garden', exact: true }).click()
  await expect(page.getByLabel('Object size', { exact: true })).toHaveValue('2')
  await page.getByRole('button', { name: 'Launch game', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Ready for a shared moment?' })).toBeVisible()
  await page.getByRole('button', { name: 'I’ve reviewed it — launch', exact: true }).click()
  await expect(page.locator('.cp-launched')).toBeVisible()
  await page.getByRole('button', { name: 'Back to editor', exact: true }).click()
  await expect(page.locator('.cp-launched')).toHaveCount(0)
})

test('memory reveals in stages, uploads stay local and save, duplicate and delete work', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Open Memory Reveal', exact: true }).click()
  await page.getByRole('button', { name: 'Start preview', exact: true }).click()
  const card = page.locator('.cp-game-object').first()
  for (let i = 1; i <= 4; i++) {
    await card.click()
    await expect(card).toHaveAttribute('aria-label', `Reveal photo 1, ${i * 25}% revealed`)
    if (i < 4) await page.waitForTimeout(700)
  }
  await expect(page.locator('.cp-stage-instruction')).toHaveText('1 memories revealed')
  const photo = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 100; canvas.height = 100; const context = canvas.getContext('2d')!; context.fillStyle = '#778f65'; context.fillRect(0, 0, 100, 100); return canvas.toDataURL('image/png').split(',')[1] })
  await page.locator('#photos').setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from(photo, 'base64') })
  await expect(page.getByText('1 photos selected', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Duplicate Memory Reveal', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Memory Reveal (copy)', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit Memory Reveal', exact: true }).click()
  await expect(page.getByText('1 photos selected', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Activities', exact: true }).click()
  await page.getByRole('button', { name: 'Delete Memory Reveal (copy)', exact: true }).click()
  await page.getByRole('button', { name: 'Delete activity', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Memory Reveal (copy)', exact: true })).toHaveCount(0)
})

test('API failures, unsupported requests and stale AI results preserve valid settings', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Open Balloon Pop', exact: true }).click()
  await page.getByLabel('Ask for a change').fill('Add voice activation')
  await page.getByRole('button', { name: 'Send request' }).click()
  await expect(page.getByRole('log')).toContainText('not available')
  await expect(page.getByLabel('Object size', { exact: true })).toHaveValue('1.2')
  await page.route('**/api/agent', route => route.fulfill({ status: 502, json: { error: 'Provider unavailable. Your game is unchanged.' } }))
  await page.getByLabel('Ask for a change').fill('Make the balloons bigger')
  await page.getByRole('button', { name: 'Send request' }).click()
  await expect(page.getByRole('alert')).toContainText('Provider unavailable')
  await expect(page.getByLabel('Object size', { exact: true })).toHaveValue('1.2')
  await page.route('**/api/agent', async route => { await new Promise(resolve => setTimeout(resolve, 1000)); await route.fulfill({ json: { patch: { size: 2 }, explanation: 'Bigger', unsupported: false, mode: 'demo' } }) })
  await page.getByLabel('Ask for a change').fill('Make bigger')
  await page.getByRole('button', { name: 'Send request' }).click()
  await page.getByLabel('Activity title').fill('Latest staff change')
  await expect(page.getByRole('alert')).toContainText('activity changed while')
  await expect(page.getByLabel('Object size', { exact: true })).toHaveValue('1.2')
  await expect(page.getByLabel('Activity title')).toHaveValue('Latest staff change')
})

