import { expect, test } from '@playwright/test'

test('timed rounds freeze on pause, show balloon totals, and start fresh on replay', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByLabel('Time limit', { exact: true }).selectOption('30')
  await page.getByRole('button', { name: 'Or try a preview' }).click()
  await page.getByRole('button', { name: 'Start preview', exact: true }).click()
  const redBalloon = page.getByRole('button', { name: 'Pop red balloon (+3)', exact: true })
  await expect(redBalloon).toBeVisible()
  await redBalloon.focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('.round-status strong')).toHaveText('1 balloon popped')
  await expect(page.locator('.score-display strong')).toHaveText('3')

  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  const pausedProgress = await page.locator('.round-status').textContent()
  await page.clock.fastForward(10000)
  expect(await page.locator('.round-status').textContent()).toBe(pausedProgress)
  await page.getByRole('button', { name: 'Continue playing' }).click()
  // Give the animation loop one active frame before advancing the clock.
  await page.clock.runFor(100)
  await page.clock.fastForward(31000)
  await expect(page.getByRole('heading', { name: 'Time’s up!' })).toBeVisible()
  await expect(page.getByText('Balloons popped', { exact: true }).locator('..').locator('dd')).toHaveText('1')
  await expect(page.getByText('Points', { exact: true }).locator('..').locator('dd')).toHaveText('3')
  await expect(page.locator('.round-record')).toContainText('1 balloon')
  await expect(page.locator('.balloon-hit:visible')).toHaveCount(0)

  await page.getByRole('button', { name: 'Play again' }).click()
  await expect(page.locator('.round-status strong')).toHaveText('0 balloons popped')
  await expect(page.locator('.score-display strong')).toHaveText('0')
  await expect(page.locator('.round-status')).toContainText('30 seconds left')
  await page.clock.runFor(100)
  await page.clock.fastForward(31000)
  await expect(page.getByRole('heading', { name: 'Time’s up!' })).toBeVisible()
  await expect(page.getByText('Balloons popped', { exact: true }).locator('..').locator('dd')).toHaveText('0')
  await expect(page.locator('.round-record')).toContainText('1 balloon')
})

test('endless ends on one missed balloon and offers replay or setup', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Round type').selectOption('endless')
  await expect(page.getByLabel('Time limit', { exact: true })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Pace', exact: true }).selectOption('24')
  await page.getByRole('button', { name: 'Or try a preview' }).click()
  await page.getByRole('button', { name: 'Start preview', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Round over', exact: true })).toBeVisible({ timeout: 15000 })
  await expect(page.getByText('Balloons popped', { exact: true }).locator('..').locator('dd')).toHaveText('0')
  await page.getByRole('button', { name: 'Play again' }).click()
  await expect(page.locator('.round-status')).toContainText('0 balloons popped')
  await expect(page.getByRole('heading', { name: 'Round over', exact: true })).toBeVisible({ timeout: 15000 })
  await page.getByRole('button', { name: 'Back to setup', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enable camera', exact: true })).toBeVisible()
})
